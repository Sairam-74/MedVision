/* global localStorage, sessionStorage, URL */
// Actual auth forms against an isolated loopback server. No videos or secrets saved.
import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';
const root=process.cwd();
const base='http://localhost:8001';
const out=path.join(root,'experiments/session_20261007_signup_redirect');
const browser=await chromium.launch({headless:true,executablePath:path.join(process.env.LOCALAPPDATA,'ms-playwright/chromium-1234/chrome-win64/chrome.exe')});
const context=await browser.newContext();
const page=await context.newPage();
const errors=[]; const checks=[];
page.on('pageerror',e=>errors.push(e.message));
const check=(value,label)=>{if(!value)throw new Error(label);checks.push(label);};
try {
  for(let i=0;i<40;i++){try{if((await context.request.get(base+'/health',{timeout:1000})).ok())break;}catch{/* Server may still be starting. */}await sleep(500);}
  await page.goto(base+'/login');
  await page.waitForFunction(()=>document.querySelector('#password')?.value.length>0);
  check(await page.getByLabel('Email',{exact:true}).inputValue()==='demo.clinician@example.invalid','actual demo email automatically filled');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('heading',{name:'Home dashboard'}).waitFor();
  checks.push('prefilled sign-in succeeds without typing credentials');
  await context.request.post(base+'/auth/logout');
  await page.goto(base+'/signup');
  await page.getByRole('heading',{name:'Sign up',exact:true}).waitFor();
  const email='browser-'+Date.now()+'@example.invalid';
  await page.getByLabel('Full name').fill('Browser Researcher');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill('original-long-passphrase');
  await page.getByLabel('Confirm password').fill('original-long-passphrase');
  await page.getByRole('button',{name:'Sign up',exact:true}).click();
  await page.waitForURL(base+'/login');
  await page.getByRole('heading',{name:'Welcome back'}).waitFor();
  checks.push('successful real signup automatically redirects to login');
  const recovery=await page.getByLabel('Recovery code',{exact:true}).textContent();
  check(recovery.length>=32,'real signup displays a new recovery code');
  check(await page.getByRole('button',{name:'Continue to sign in'}).count()===0,'no intermediate confirmation required');
  check(await page.getByLabel('Email',{exact:true}).inputValue()===email,'signup routes to the new account email');
  check(await page.getByLabel('Password',{exact:true}).inputValue()==='','demo prefill does not overwrite a new account');
  await page.goto(base+'/signup');
  await page.getByLabel('Full name').fill('Duplicate Researcher');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill('original-long-passphrase');
  await page.getByLabel('Confirm password').fill('original-long-passphrase');
  await page.getByRole('button',{name:'Sign up',exact:true}).click();
  await page.getByText('An account already uses this email',{exact:true}).waitFor();
  check(new URL(page.url()).pathname==='/signup','failed duplicate signup stays on the form with an error');
  await page.goto(base+'/login');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill('original-long-passphrase');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('heading',{name:'Home dashboard'}).waitFor();
  checks.push('newly registered account signs in');
  check(await page.evaluate(()=>!Object.values(localStorage).some(v=>v.includes('recoveryCode'))&&!Object.values(sessionStorage).some(v=>v.includes('recoveryCode'))),'recovery receipt is not persisted in browser storage');
  const oldCookie=(await context.cookies()).find(c=>c.name==='medvision_session');
  await page.goto(base+'/forgot-password');
  await page.getByLabel('Work email').fill(email);
  await page.getByLabel('Recovery code',{exact:true}).fill('incorrect-recovery-code-long');
  await page.getByRole('button',{name:'Verify recovery code'}).click();
  await page.getByText('Email or recovery code is incorrect',{exact:true}).waitFor();
  checks.push('wrong recovery proof shows a clear error');
  await page.getByLabel('Recovery code',{exact:true}).fill(recovery);
  await page.getByRole('button',{name:'Verify recovery code'}).click();
  await page.getByRole('heading',{name:'Choose a new password'}).waitFor();
  check(new URL(page.url()).hash.startsWith('#token='),'reset token travels in a fragment, not server request logs');
  await page.getByLabel('New password',{exact:true}).fill('replacement-long-passphrase');
  await page.getByLabel('Confirm password').fill('replacement-long-passphrase');
  await page.getByRole('button',{name:'Reset password',exact:true}).click();
  await page.getByRole('heading',{name:'Password updated'}).waitFor();
  const renewed=await page.getByLabel('New recovery code').textContent();
  check(renewed.length>=32&&renewed!==recovery,'successful reset shows a renewed recovery code');
  check(!page.url().includes('token='),'used reset token removed from visible URL');
  const outsider=await browser.newContext();
  await outsider.addCookies([oldCookie]);
  check((await outsider.request.get(base+'/analyses')).status()===401,'password reset revokes an independently retained old session');
  await outsider.close();
  await page.getByRole('link',{name:'Return to sign in'}).click();
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill('original-long-passphrase');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByText('Invalid credentials',{exact:true}).waitFor();
  checks.push('old password is rejected after resetting');
  await page.getByLabel('Password',{exact:true}).fill('replacement-long-passphrase');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('heading',{name:'Home dashboard'}).waitFor();
  checks.push('replacement password signs in through the actual form');
  await page.goto(base+'/reset-password');
  await page.getByRole('heading',{name:'Reset link required'}).waitFor();
  checks.push('missing reset token cannot display a usable reset form');
  // Finally verify prefill against the owner's actual running demo, without changing it.
  const real=await browser.newContext();const realPage=await real.newPage();
  await realPage.goto('http://localhost:8000/login');
  await realPage.waitForFunction(()=>document.querySelector('#password')?.value.length>0);
  await realPage.getByRole('button',{name:'Sign in',exact:true}).click();
  await realPage.getByRole('heading',{name:'Home dashboard'}).waitFor();
  checks.push('owner demo signs in with automatic prefill and preserves existing history');
  await realPage.screenshot({path:path.join(out,'actual_demo_dashboard.png'),fullPage:true});
  await real.close();
  check(errors.length===0,'no authentication-page browser runtime errors');
  await fs.writeFile(path.join(out,'browser_auth_checks.json'),JSON.stringify({checks_passed:checks.length,checks,temporary_accounts_only:true,no_secrets_or_recovery_codes_recorded:true},null,2));
  console.log('Browser authentication checks passed:',checks.length);
}finally{await context.close();await browser.close();}
